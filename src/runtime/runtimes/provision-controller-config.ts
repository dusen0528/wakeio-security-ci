import { createHash } from 'node:crypto';
import { requireProvision } from './provision-types.js';

export interface ProvisionHelper {
  readonly name: string;
  readonly body: Buffer;
  readonly sha256: string;
  readonly installation: 'controller' | 'install';
}

// Pinned 1.0.3 boot/20-rootless-base.sh otherwise changes guest-wide sysctls/delegation.
// Cloud-init bootcmd runs before those scripts. Existing unknown files are never overwritten.
const BOOT_POLICY = `#!/bin/sh
set -eu
umask 077
test ! -e /etc/sysctl.d/99-lima.conf
test ! -e /etc/systemd/system/user@.service.d/lima.conf
mkdir -p /etc/systemd/system/user@.service.d
printf '%s\\n' '# Keep image kernel policy; use the authenticated package scoped profile.' > /etc/sysctl.d/99-lima.conf
printf '[Service]\\nDelegate=no\\n' > /etc/systemd/system/user@.service.d/lima.conf
`;

/** Generated bytes are separately reviewable; a vendor catalog cannot approve them. */
export function provisionBootstrap(helpers: readonly ProvisionHelper[], nonce: string): string {
  requireProvision(/^[a-f0-9]{64}$/.test(nonce) && helpers.length > 0 && helpers.length <= 64,
    'helper_manifest_invalid');
  const names = new Set<string>();
  const manifest = helpers.map(helper => {
    requireProvision(/^(?:[a-z][a-z0-9_-]*\/)*[a-z][a-z0-9_-]*\.(?:py|mjs|js|json)$/.test(helper.name)
      && !names.has(helper.name) && helper.body.length <= 128 * 1024, 'helper_manifest_invalid');
    names.add(helper.name);
    requireProvision(createHash('sha256').update(helper.body).digest('hex') === helper.sha256,
      'helper_digest_mismatch');
    return { name: helper.name, installation: helper.installation, sha256: helper.sha256,
      body: helper.body.toString('base64') };
  });
  const encoded = Buffer.from(JSON.stringify(manifest)).toString('base64');
  const bindings = Buffer.from(JSON.stringify(manifest.map(({ name, installation, sha256 }) =>
    ({ name, installation, sha256 })))).toString('base64');
  return '#!/bin/sh\nset -eu\numask 077\n/usr/bin/python3 -I - <<\'WAKEIO_FIXED_BOOT\'\n'
    + 'import base64, hashlib, json, os\n'
    + `items = json.loads(base64.b64decode('${encoded}', validate=True))\n`
    + "for root in ('/usr/local/lib/wakeio-controller', '/usr/local/lib/wakeio-install',\n"
    + "             '/usr/local/lib/wakeio-controller/build'):\n"
    + '    os.mkdir(root, 0o700)\n'
    + 'for item in items:\n'
    + "    root = '/usr/local/lib/wakeio-' + item['installation']\n"
    + "    data = base64.b64decode(item['body'], validate=True)\n"
    + "    if hashlib.sha256(data).hexdigest() != item['sha256']: raise SystemExit(125)\n"
    + "    os.makedirs(os.path.dirname(root + '/' + item['name']), mode=0o700, exist_ok=True)\n"
    + "    with open(root + '/' + item['name'], 'xb') as f:\n"
    + "        os.fchmod(f.fileno(), 0o755 if item['name'] == 'install_hook.py' else 0o644)\n"
    + '        f.write(data)\n'
    + "with open('/usr/local/lib/wakeio-controller/manifest.json', 'xb') as f:\n"
    + "    os.fchmod(f.fileno(), 0o600)\n"
    + `    f.write(base64.b64decode('${bindings}', validate=True))\n`
    + "with open('/usr/local/lib/wakeio-controller/session', 'x') as f:\n"
    + "    os.fchmod(f.fileno(), 0o600)\n"
    + `    f.write('${nonce}')\n`
    + "for root in ('/usr/local/lib/wakeio-controller', '/usr/local/lib/wakeio-controller/build'):\n"
    + "    os.chown(root, 0, 10001)\n"
    + "    os.chmod(root, 0o750)\n"
    + "os.execv('/usr/bin/python3', ['/usr/bin/python3', '-I', '-B', "
    + "'/usr/local/lib/wakeio-controller/bootstrap.py'])\nWAKEIO_FIXED_BOOT\n";
}

/** Narrow adaptation of immutable M1 compileLimaProfileConfig, with the approved aggregate sizing. */
export function provisionVmConfig(rootfs: string, bootstrap: string): string {
  requireProvision(rootfs.startsWith('/private/tmp/') && !/[\0\r\n]/.test(rootfs), 'rootfs_path_invalid');
  return JSON.stringify({
    minimumLimaVersion: '1.0.3', vmType: 'vz', arch: 'aarch64',
    images: [{ location: rootfs, arch: 'aarch64',
      digest: 'sha256:50e24e1fb79e89116e939d90aa7738f7af48c442fa1bc2510131e0b39c50348e' }],
    cpus: 6, memory: '8GiB', disk: '40GiB', mounts: [], additionalDisks: [], networks: [],
    upgradePackages: false, copyToHost: [], propagateProxyEnv: false,
    ssh: { forwardAgent: false, loadDotSSHPubKeys: false, forwardX11: false, forwardX11Trusted: false },
    hostResolver: { enabled: false, hosts: {} },
    env: { ftp_proxy: '', http_proxy: '', https_proxy: '', no_proxy: '',
      FTP_PROXY: '', HTTP_PROXY: '', HTTPS_PROXY: '', NO_PROXY: '' },
    containerd: { system: false, user: false }, rosetta: { enabled: false, binfmt: false },
    user: { name: 'wakeio-admin', uid: 10000, home: '/home/wakeio-admin' },
    portForwards: [
      { guestSocket: '/run/wakeio-m1/relay.sock', hostSocket: '{{.Dir}}/sock/docker.sock' },
      { guestIP: '0.0.0.0', guestPortRange: [1, 65535], proto: 'any', ignore: true },
    ],
    provision: [{ mode: 'boot', script: BOOT_POLICY },
      { mode: 'dependency', skipDefaultDependencyResolution: true },
      { mode: 'system', script: bootstrap }],
  }) + '\n';
}
